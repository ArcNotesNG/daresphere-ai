import os, threading, requests, urllib.parse
from flask import Flask
from groq import Groq
from telegram import Update
from telegram.ext import Application, CommandHandler, MessageHandler, filters, ContextTypes

flask_app = Flask(__name__)
@flask_app.route('/')
def home():
    return "DareSphere AI Live with Real Images!"
def run_flask():
    port = int(os.environ.get("PORT", 10000))
    flask_app.run(host="0.0.0.0", port=port)

TOKEN = os.getenv("BOT_TOKEN")
GROQ_KEY = os.getenv("GROQ_API_KEY")
client = Groq(api_key=GROQ_KEY)

SYSTEM_PROMPT = "You are DareSphere AI, built by Dare Samuel Olusegun, dedicated to Inemisit Dare (GLOWED). You are helpful like ChatGPT. IMPORTANT: You cannot generate images yourself. If user asks for picture/image/photo, say you will generate it."

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    context.chat_data["history"] = []
    await update.message.reply_text("Hey Boss! 🔥 DareSphere AI Ready!\n\n✅ Text Chat\n✅ Voice Notes 🎤\n✅ REAL Image Generation 🎨\n\nJust say:\n'Normal car picture' → I will send REAL photo!\n\nGOD DID! 🙏")

async def generate_real_image(update: Update, prompt: str):
    await update.message.reply_text(f"🎨 Generating REAL image: {prompt}...")
    try:
        encoded = urllib.parse.quote(prompt)
        image_url = f"https://image.pollinations.ai/prompt/{encoded}?width=1024&height=1024&model=flux&nologo=true"
        await update.message.reply_photo(photo=image_url, caption=f"🚗 {prompt}\n\nGenerated by DareSphere AI ✨ GOD DID!")
    except Exception as e:
        await update.message.reply_text(f"Image Error: {e}")

async def handle_text_logic(text, update, context):
    if "history" not in context.chat_data:
        context.chat_data["history"] = []
    context.chat_data["history"].append({"role": "user", "content": text})
    history = context.chat_data["history"][-10:]
    messages = [{"role": "system", "content": SYSTEM_PROMPT}] + history
    res = client.chat.completions.create(model="openai/gpt-oss-20b", messages=messages, max_tokens=700)
    reply = res.choices[0].message.content
    context.chat_data["history"].append({"role": "assistant", "content": reply})
    await update.message.reply_text(reply)

async def chat(update: Update, context: ContextTypes.DEFAULT_TYPE):
    text = update.message.text
    low = text.lower()
    # If user wants picture/image/photo/car picture etc - GENERATE REAL IMAGE
    image_keywords = ["picture", "image", "photo", "generate", "draw", "create image", "car picture", "normal car"]
    if any(k in low for k in image_keywords):
        prompt = text.replace("picture","").replace("image","").replace("generate","").replace("normal","").strip()
        if len(prompt) < 3:
            prompt = text
        # Make it better prompt
        if "car" in low:
            prompt = f"{prompt}, photorealistic, high quality, 4k, real car"
        await generate_real_image(update, prompt)
    else:
        await handle_text_logic(text, update, context)

async def voice_chat(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text("🎧 Listening...")
    try:
        vf = await update.message.voice.get_file()
        path = f"/tmp/{vf.file_id}.ogg"
        await vf.download_to_drive(path)
        with open(path, "rb") as f:
            t = client.audio.transcriptions.create(file=(path, f.read()), model="whisper-large-v3")
        text = t.text
        await update.message.reply_text(f"🎤 You said: {text}")
        low = text.lower()
        if any(k in low for k in ["picture","image","photo","car"]):
            await generate_real_image(update, text)
        else:
            await handle_text_logic(text, update, context)
        os.remove(path)
    except Exception as e:
        await update.message.reply_text(f"Voice Error: {e}")

async def post_init(app):
    await app.bot.delete_webhook(drop_pending_updates=True)

def main():
    threading.Thread(target=run_flask, daemon=True).start()
    app = Application.builder().token(TOKEN).post_init(post_init).build()
    app.add_handler(CommandHandler("start", start))
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, chat))
    app.add_handler(MessageHandler(filters.VOICE, voice_chat))
    app.run_polling(drop_pending_updates=True)

if __name__ == "__main__":
    main()
